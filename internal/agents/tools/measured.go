var releases = []string{schedule.Inflation, schedule.Jobs, schedule.Rates}

func releaseMeasured(entries []schedule.Entry) string {
	for _, e := range entries {
		if slices.Contains(releases, e.Kind) {
			return macroMeasured
		}
	}

	return ""
}

func unlocksMeasured(entries []schedule.Entry) string {
	for _, e := range entries {
		if e.Kind == schedule.Unlock {
			return unlockMeasured
		}
	}

	return ""
}

func measured(coin radar.Coin) []string {
	var notes []string

	if coin.Trend != nil {
		notes = append(notes, trendMeasured)
	}

	if coin.Launch != nil {
		notes = append(notes, launchMeasured)
	}

	if coin.Wake != nil {
		notes = append(notes, wokeMeasured)
	}

	return notes
}
